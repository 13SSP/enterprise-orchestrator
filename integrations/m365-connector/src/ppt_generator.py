"""
cortex.ai - PowerPoint .pptx Presentation Generator
Generates clean, professionally branded Microsoft PowerPoint (.pptx) presentations from outline JSON.
"""

from pathlib import Path
from typing import List, Dict, Any, Optional
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor

def generate_pptx_deck(
    deck_title: str,
    slides: List[Dict[str, Any]],
    output_path: Path,
    deck_subtitle: Optional[str] = "Generated by cortex.ai"
) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    prs = Presentation()

    # Slide 1: Title Slide (layout 0)
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    title = slide.shapes.title
    subtitle = slide.placeholders[1]
    title.text = deck_title
    subtitle.text = deck_subtitle or "cortex.ai Multi-Agent Enterprise Intelligence"

    # Slide 2..N: Content Slides (layout 1: Title and Content)
    bullet_slide_layout = prs.slide_layouts[1]
    for s_data in slides:
        slide = prs.slides.add_slide(bullet_slide_layout)
        shapes = slide.shapes
        title_shape = shapes.title
        body_shape = shapes.placeholders[1]

        title_shape.text = s_data.get("title", "Slide Title")
        tf = body_shape.text_frame
        tf.word_wrap = True

        bullets = s_data.get("bullets", [])
        if bullets:
            tf.text = bullets[0]
            for b in bullets[1:]:
                p = tf.add_paragraph()
                p.text = b
                p.level = 0
        else:
            tf.text = s_data.get("content", "")

        # Speaker notes if present
        notes = s_data.get("speaker_notes")
        if notes:
            notes_slide = slide.notes_slide
            text_frame = notes_slide.notes_text_frame
            text_frame.text = notes

    prs.save(str(output_path))
    return output_path
