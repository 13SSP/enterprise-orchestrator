"""
cortex.ai - Word .docx Document Generator
Generates clean, professionally formatted Microsoft Word (.docx) documents from structured outline JSON.
"""

import os
from pathlib import Path
from typing import List, Dict, Any, Optional
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

def generate_docx_document(
    title: str,
    sections: List[Dict[str, Any]],
    output_path: Path,
    subtitle: Optional[str] = None,
    author: Optional[str] = "cortex.ai Productivity Agent"
) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc = docx.Document()

    # Title
    title_p = doc.add_paragraph()
    title_run = title_p.add_run(title)
    title_run.font.size = Pt(24)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(26, 86, 219) # Primary Blue
    title_p.paragraph_format.space_after = Pt(4)

    # Subtitle
    if subtitle:
        sub_p = doc.add_paragraph()
        sub_run = sub_p.add_run(subtitle)
        sub_run.font.size = Pt(13)
        sub_run.font.italic = True
        sub_run.font.color.rgb = RGBColor(107, 114, 128)
        sub_p.paragraph_format.space_after = Pt(16)

    # Meta
    meta_p = doc.add_paragraph()
    meta_run = meta_p.add_run(f"Generated by: {author}")
    meta_run.font.size = Pt(9)
    meta_run.font.color.rgb = RGBColor(156, 163, 175)
    doc.add_paragraph() # Spacing

    # Sections
    for sec in sections:
        heading = sec.get("heading", "Section")
        doc.add_heading(heading, level=1)
        
        content = sec.get("content", "")
        if content:
            doc.add_paragraph(content)

        bullets = sec.get("bullets", [])
        for b in bullets:
            doc.add_paragraph(b, style='List Bullet')

    doc.save(str(output_path))
    return output_path
